"""Frozen CP v2 calibration, shared by every task category."""
VERSION = 'cp_v2_semantic_preservation_20261115'

OLD_SCALE = '''- 5：应保留的内容一致，没有实质性的无关变化。
- 4：应保留的内容整体一致，仅有轻微偏差，核心内容没有明显改变。
- 3：重要内容有明显变化，但未严重破坏核心内容，整体大体保留。
- 2：一个核心内容严重丢失或改变，或多项重要内容发生重大变化，仍有部分应保留内容保留下来。
- 1：应保留的内容整体或绝大部分丢失、被替换。'''

NEW_SCALE = '''- 5：非目标内容在语义和感知上充分保留。允许不改变人物、物体、动作与场景辨识的微小纹理、色调、边缘、局部细节或短暂轻微波动；不要求逐像素一致，也不要求视觉上毫无差异。
- 4：非目标内容总体保留，但有明确可见、超出上述可忽略差异的局部内容偏移；核心人物、物体、动作与场景仍保持。必须指出具体哪个非目标内容发生了什么变化，不能仅以“有细微差异”扣为4。
- 3：一项重要的非目标内容发生明显、持续的改变或损失，但主要来源内容仍可识别。
- 2：核心非目标内容严重改变或丢失，或多项重要内容大范围改变；仍保留部分来源内容。
- 1：非目标内容整体或绝大部分丢失、被替换，几乎无法辨认原视频应保留的主体内容。只有这种严重破坏才给1；编辑失败本身绝不是给1的理由。'''

POLICY = '''
### CP独立判分规则（优先于含糊的“差异”描述）

本项衡量非目标内容保持，不衡量编辑成功。先按原始指令确定允许编辑的对象、属性和范围，再比较其余内容。目标属性是否改变、是否改对、是否与参考匹配，以及目标属性随时间是否稳定，均由独立的指令遵循分评价，不得在CP重复扣分。

- 输出几乎等于源视频、编辑完全没生效：若非目标内容保留良好，CP应给5；若另有可见的非目标损失，才按该损失降低CP。
- 目标修改方向错误或目标属性不匹配：例如要求红发却生成蓝发，若其余应保留内容一致，CP仍应给5。不能因为发色错误、目标衣服不对、目标背景不对或动作未完成而降低CP。
- 允许编辑范围由指令决定，不因编辑失败而取消。编辑区域内仍须保留的其他属性继续比较；例如改发色却明显换了脸，换脸仍应影响CP。修改了错误对象而破坏本应保留的内容，也应扣CP。
- 正常生成造成的微小纹理、高光、色调、边缘、褶皱细节差异，以及不改变内容辨识的短暂轻微波动，可以给5。不要把5理解为像素完全相同；不要为了保守而默认给4。
- 指令允许的编辑及其直接、合理的轮廓、局部阴影、反射、遮挡或可见范围变化不扣CP。不得把其他人物、物体或场景的大范围替换解释为合理关联变化。
- 每个低于5的评分必须有可见的非目标内容变化作为依据，结合重要性、程度和持续范围判断。不要根据“编辑看起来失败”推断其他内容也被破坏，也不要凭空推断不可见内容发生变化。

判分示例（两项分数相互独立）：
1. 要求换衣，但输出仍穿原衣，人物、动作、镜头、背景保持：IF低分，CP=5。
2. 要求红发，输出蓝发，其他内容保持，仅有轻微纹理差异：IF低分，CP=5。
3. 要求换背景，人物与动作保留，衣服仅有细小褶皱或明暗差异：CP=5。
4. 要求改发色，却把另一名非目标人物明显换了身份：CP按非目标人物损失扣分，即使目标发色正确也不能给5。

只输出score和reason两行。reason引用实际可见的P帧号，说明非目标内容是否保留；如扣分，明确指出非目标对象或属性及变化，不以目标编辑失败、目标不匹配或笼统的“略有差异”作为扣分依据。
'''

def calibrate(text):
    assert text.count(OLD_SCALE) == 1, 'unexpected upstream CP anchors'
    return text.replace(OLD_SCALE, NEW_SCALE).replace('P00–P15', 'P00至P(K-1)') + POLICY

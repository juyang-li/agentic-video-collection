"""Offline regression tests: official payload, score formula, cache, and failures."""

import base64
from copy import deepcopy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import judge_spatial_openrouter as judge


def response(accuracy=5):
    return {"model": judge.MODEL, "provider": judge.PROVIDER, "choices": [{
        "finish_reason": "stop", "message": {"content": json.dumps({
            "accuracy": accuracy, "preservation": 5, "realism": 5,
            "consistency": 5, "reason": "test"})}}],
        "usage": {"prompt_tokens": 100, "completion_tokens": 20, "total_tokens": 120, "cost": 0.001}}


class JudgeTests(unittest.TestCase):
    def test_vertex_is_explicit_separate_protocol(self):
        original, _ = judge.protocol()
        try:
            judge.configure_route("vertex")
            vertex, _ = judge.protocol()
            self.assertEqual(vertex["expected_response_provider"], "Google")
            self.assertEqual(vertex["settings"]["provider"]["only"], ["google-vertex/global"])
            self.assertNotEqual(vertex["protocol"], original["protocol"])
            self.assertNotEqual(judge.digest(vertex), judge.digest(original))
            self.assertFalse(vertex["settings"]["provider"]["allow_fallbacks"])
        finally:
            judge.configure_route("studio")

    def test_temperature_zero_is_explicit_separate_protocol(self):
        original, _ = judge.protocol()
        try:
            judge.configure_route("vertex", temperature_zero=True)
            temp0, _ = judge.protocol()
            self.assertEqual(temp0["settings"]["temperature"], 0.0)
            self.assertTrue(temp0["protocol"].endswith("_temp0_v1"))
            self.assertNotEqual(judge.digest(temp0), judge.digest(original))
        finally:
            judge.configure_route("studio")

    def test_formula(self):
        for accuracy in range(6):
            self.assertEqual(judge.parse_score(response(accuracy))["overall_score"], accuracy)

    def test_invalid(self):
        for accuracy in (-1, 6, True, 2.5, "3"):
            with self.assertRaises(ValueError):
                judge.parse_score(response(accuracy))
        for field, value in (("model", "wrong"), ("provider", "wrong")):
            body = response(); body[field] = value
            with self.assertRaises(ValueError):
                judge.parse_score(body)
        body = response(); body["choices"][0]["finish_reason"] = "length"
        with self.assertRaises(ValueError):
            judge.parse_score(body)

    def test_full_mp4_payload_and_resume(self):
        metadata, rules = judge.protocol()
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source, generated = root / "source.mp4", root / "generated.mp4"
            source.write_bytes(b"source bytes"); generated.write_bytes(b"generated bytes")
            task = {"sample_id": "sample", "source_path": str(source),
                    "generated_video": str(generated), "instruction": "Edit it."}
            payload = judge.payload_for(task, rules)
            content = payload["messages"][0]["content"]
            self.assertEqual(len(content), 5)
            self.assertEqual(content[0]["text"], f"Evaluation System Rules:\n{rules}\n\nUser Edit Instruction: Edit it.\n")
            self.assertEqual(content[1]["text"], "Original Video (Reference):")
            self.assertEqual(content[3]["text"], "Edited Video (Target):")
            for index, path in ((2, source), (4, generated)):
                self.assertEqual(base64.b64decode(content[index]["video_url"]["url"].split(",", 1)[1]), path.read_bytes())
            self.assertEqual(payload["reasoning"]["effort"], "low")
            self.assertFalse(payload["provider"]["allow_fallbacks"])
            self.assertNotIn("temperature", payload)
            with patch.object(judge.requests.Session, "post") as post:
                post.return_value.status_code = 200
                post.return_value.ok = True
                post.return_value.json.return_value = response()
                result = judge.evaluate(task, root / "scores", metadata, rules, "test_secret", 4)
                self.assertEqual(result["status"], "success")
                judge.evaluate(task, root / "scores", metadata, rules, "test_secret", 4)
                self.assertEqual(post.call_count, 1)
                summary = judge.summarize(root / "scores", [task], [result])
                self.assertEqual(summary["tasks_succeeded"], 1)
                self.assertEqual(summary["reported_cost_usd_known_requests"], 0.001)


if __name__ == "__main__":
    unittest.main()
